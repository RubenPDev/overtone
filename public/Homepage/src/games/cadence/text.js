/** A tune's name, clue and solved note, in the language in use. */
export function tuneText(melody) {
  const es = getLang() === 'es' ? ES[melody.title] : null;
  return es
    ? { title: es[0], intro: es[1], solved: es[2] }
    : { title: melody.title, intro: melody.intro, solved: melody.solved };
}

/** For checking: tunes with no Spanish yet. */
export const untranslatedTunes = (melodies) => melodies.filter((m) => !ES[m.title]).map((m) => m.title);
